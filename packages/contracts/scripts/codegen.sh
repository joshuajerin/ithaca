#!/usr/bin/env bash
# Regenerate pydantic models (and zod schemas) from the JSON-Schema source of truth.
# The generated outputs are committed; CI runs this then `git diff --exit-code` (see check_drift.sh)
# so a schema change without regen — or a hand-edit of generated code — turns the build red.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # packages/contracts
cd "$HERE"

# Pinned tool versions => deterministic output across machines (drift gate depends on this).
DATAMODEL_CODEGEN_VERSION="${DATAMODEL_CODEGEN_VERSION:-0.26.3}"
BLACK_VERSION="${BLACK_VERSION:-24.10.0}"   # pin the formatter too: datamodel-codegen runs black, so a floating black would false-trip the drift gate
JSON_SCHEMA_TO_ZOD_VERSION="${JSON_SCHEMA_TO_ZOD_VERSION:-2.4.1}"

# name<TAB>ClassName  (root model class is forced for determinism)
SCHEMAS=(
  "tenant:TenantContext"
  "auth:AuthPrincipal"
  "provenance:ProvenanceEnvelope"
  "events:TraceEvent"
  "strategy_spec:StrategySpec"
  "skill_manifest:SkillManifest"
  "platform_run:PlatformRun"
  "provider_entitlement:ProviderEntitlement"
  "trigger_policy:TriggerPolicy"
  "execution:ExecutionRecord"
  "platform_error:PlatformError"
)

echo "==> Generating pydantic v2 models (datamodel-code-generator ${DATAMODEL_CODEGEN_VERSION})"
PY_OUT="py/doomberg_contracts/generated"
mkdir -p "$PY_OUT"
for entry in "${SCHEMAS[@]}"; do
  name="${entry%%:*}"; cls="${entry##*:}"
  uvx --from "datamodel-code-generator==${DATAMODEL_CODEGEN_VERSION}" --with "black==${BLACK_VERSION}" datamodel-codegen \
    --input "schema/${name}.schema.json" \
    --input-file-type jsonschema \
    --output "${PY_OUT}/${name}.py" \
    --output-model-type pydantic_v2.BaseModel \
    --class-name "${cls}" \
    --target-python-version 3.11 \
    --use-standard-collections \
    --use-union-operator \
    --use-schema-description \
    --use-field-description \
    --use-double-quotes \
    --field-constraints \
    --disable-timestamp
done
python3 scripts/_patch_pydantic_optional_nulls.py

# Re-export every generated root model from the package __init__ (deterministic order).
cat > "py/doomberg_contracts/generated/__init__.py" <<'EOF'
"""GENERATED by scripts/codegen.sh from ../schema/*.schema.json. Do not edit by hand."""
from .auth import AuthPrincipal
from .events import TraceEvent
from .execution import ExecutionRecord
from .platform_error import PlatformError
from .platform_run import PlatformRun
from .provenance import ProvenanceEnvelope
from .provider_entitlement import ProviderEntitlement
from .skill_manifest import SkillManifest
from .strategy_spec import StrategySpec
from .tenant import TenantContext
from .trigger_policy import TriggerPolicy

__all__ = [
    "AuthPrincipal",
    "ExecutionRecord",
    "PlatformError",
    "PlatformRun",
    "ProvenanceEnvelope",
    "ProviderEntitlement",
    "SkillManifest",
    "StrategySpec",
    "TenantContext",
    "TraceEvent",
    "TriggerPolicy",
]
EOF

echo "==> Generating zod schemas (json-schema-to-zod ${JSON_SCHEMA_TO_ZOD_VERSION})"
TS_OUT="ts/src/generated"
mkdir -p "$TS_OUT"
DEREF_DIR="$(mktemp -d)"
trap 'rm -rf "$DEREF_DIR"' EXIT
for entry in "${SCHEMAS[@]}"; do
  name="${entry%%:*}"; cls="${entry##*:}"
  # json-schema-to-zod does not resolve 2020-12 $defs; inline them first so zod
  # validation is as deep as the pydantic side (keeps the two languages consistent).
  python3 scripts/_deref.py "schema/${name}.schema.json" "${DEREF_DIR}/${name}.json"
  npx --yes "json-schema-to-zod@${JSON_SCHEMA_TO_ZOD_VERSION}" \
    --input "${DEREF_DIR}/${name}.json" \
    --output "${TS_OUT}/${name}.ts" \
    --name "${cls}"
done

cat > "${TS_OUT}/index.ts" <<'EOF'
// GENERATED by scripts/codegen.sh from ../schema/*.schema.json. Do not edit by hand.
export { AuthPrincipal } from "./auth";
export { TraceEvent } from "./events";
export { ExecutionRecord } from "./execution";
export { PlatformError } from "./platform_error";
export { PlatformRun } from "./platform_run";
export { ProvenanceEnvelope } from "./provenance";
export { ProviderEntitlement } from "./provider_entitlement";
export { SkillManifest } from "./skill_manifest";
export { StrategySpec } from "./strategy_spec";
export { TenantContext } from "./tenant";
export { TriggerPolicy } from "./trigger_policy";
EOF

echo "==> codegen complete"
